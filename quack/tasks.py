"""Append to and parse TASKS.md."""

from __future__ import annotations

import hashlib
import re
from datetime import date
from pathlib import Path

from .models import Task
from .safety import assert_writable

HEADER = "# Quack Tasks\n\n*Generated by Quack. The duck never modifies your code.*\n"
_SECTIONS = (("critical", "## Critical"), ("suggestion", "## Suggestions"))
_ID = re.compile(r"<!-- id:([0-9a-f]{8}) -->")
_DONE = re.compile(r"^- \[[xX]\] `(?P<loc>[^`]+)`.*$", re.M)
_OPEN = re.compile(r"^- \[ \] `(?P<loc>[^`]+)`.*$", re.M)


def _hash8(description: str) -> str:
    return hashlib.sha256(" ".join(description.split()).encode()).hexdigest()[:8]


def task_id(t: Task) -> str:
    return f"{t.file}:{t.line}:{_hash8(t.description)}"


def _split(text: str) -> tuple[str, dict[str, list[list[str]]]]:
    """Return (header, {severity: [item_lines, ...]}) from an existing file."""
    header_lines: list[str] = []
    items: dict[str, list[list[str]]] = {"critical": [], "suggestion": []}
    current: str | None = None
    for line in text.splitlines():
        if line.startswith("## "):
            current = "critical" if line.strip() == "## Critical" else "suggestion"
            continue
        if current is None:
            header_lines.append(line)
        elif line.startswith("- ["):
            items[current].append([line])
        elif line.strip() and items[current]:
            items[current][-1].append(line)
    return "\n".join(header_lines).rstrip() + "\n", items


def append_tasks(tasks_md: Path, tasks: list[Task], source_question: str) -> list[str]:
    """Add tasks (deduplicated) and return the ids of all given tasks."""
    assert_writable(tasks_md)
    tasks_md = Path(tasks_md)
    header, items = _split(tasks_md.read_text(encoding="utf-8")) if tasks_md.exists() else (HEADER, {"critical": [], "suggestion": []})
    existing_open = {
        (m.group("loc"), _ID.search(m.group(0)).group(1))  # type: ignore[union-attr]
        for sev in items.values() for item in sev for m in [_OPEN.match(item[0])] if m and _ID.search(item[0])
    }
    ids: list[str] = []
    today = date.today().isoformat()
    for t in tasks:
        h = _hash8(t.description)
        loc = f"{t.file}:{t.line}"
        ids.append(f"{loc}:{h}")
        if (loc, h) in existing_open:
            continue
        desc = " ".join(t.description.split())
        why = " ".join(t.why.split())
        items[t.severity].append([
            f"- [ ] `{loc}` — {desc} <!-- id:{h} -->",
            f"  - Why: {why}",
            f"  - Asked: {today}",
        ])
        existing_open.add((loc, h))
    out = [header.rstrip("\n"), ""]
    for sev, title in _SECTIONS:
        if items[sev]:
            out += [title, ""]
            for item in items[sev]:
                out += item
            out.append("")
    tasks_md.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    return ids


def parse_completed(tasks_md: Path) -> list[str]:
    """Return ids (``file:line[:hash8]``) of tasks ticked ``[x]``."""
    tasks_md = Path(tasks_md)
    if not tasks_md.exists():
        return []
    out = []
    for m in _DONE.finditer(tasks_md.read_text(encoding="utf-8")):
        h = _ID.search(m.group(0))
        out.append(f"{m.group('loc')}:{h.group(1)}" if h else m.group("loc"))
    return out
